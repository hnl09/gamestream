//! Tradução PT/EN da interface e das mensagens. O português é o texto-fonte no código; `t()` devolve
//! a versão do idioma escolhido. Textos com valores usam `tr!("pt {x}", "en {x}", ...)`.
//! (Tabela gerada; para incluir um texto novo, adicione o par aqui.)

use std::{collections::HashMap, sync::LazyLock};

pub use crate::settings::is_en;

static TABLE: LazyLock<HashMap<&'static str, &'static str>> = LazyLock::new(|| PAIRS.iter().copied().collect());

/// Texto no idioma atual (o argumento é o texto em português).
pub fn t(pt: &'static str) -> &'static str {
    if is_en() {
        TABLE.get(pt).copied().unwrap_or(pt)
    } else {
        pt
    }
}

/// Tradução de um texto vindo de fora (ex.: motivo enviado pelo transmissor).
pub fn t_dyn(pt: &str) -> String {
    if is_en() {
        TABLE.get(pt).copied().unwrap_or(pt).to_string()
    } else {
        pt.to_string()
    }
}

/// `format!` com versões em português e inglês (mesmos marcadores, na mesma ordem).
#[macro_export]
macro_rules! tr {
    ($pt:literal, $en:literal $(, $arg:expr)* $(,)?) => {
        if $crate::i18n::is_en() { format!($en $(, $arg)*) } else { format!($pt $(, $arg)*) }
    };
}

